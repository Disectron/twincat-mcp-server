"""Code generators from the runtime datatype table and symbol table.

For the MES / HMI side: exact C# structs (explicit field offsets from the
datatype table, so marshalling matches the PLC byte for byte), TypeScript
interfaces, JSON type descriptions, and symbol constant files.
"""
from __future__ import annotations

import json
import re
from typing import Any

from .ads_types import TypeSystem, DtEntry, F_REFERENCETO
from . import types_tc as T

CS_SCALAR = {
    "BOOL": ("bool", "[MarshalAs(UnmanagedType.U1)] "), "BYTE": ("byte", ""), "USINT": ("byte", ""), "SINT": ("sbyte", ""),
    "WORD": ("ushort", ""), "UINT": ("ushort", ""), "INT": ("short", ""), "DWORD": ("uint", ""), "UDINT": ("uint", ""),
    "DINT": ("int", ""), "LWORD": ("ulong", ""), "ULINT": ("ulong", ""), "LINT": ("long", ""),
    "REAL": ("float", ""), "LREAL": ("double", ""), "TIME": ("uint", ""), "LTIME": ("ulong", ""), "DATE": ("uint", ""),
    "DT": ("uint", ""), "DATE_AND_TIME": ("uint", ""), "TOD": ("uint", ""), "TIME_OF_DAY": ("uint", ""),
    "LDATE": ("ulong", ""), "LDT": ("ulong", ""), "LTOD": ("ulong", ""),
}
TS_SCALAR = {k: ("boolean" if k == "BOOL" else "number") for k in CS_SCALAR}
TS_SCALAR.update({"LWORD": "bigint", "ULINT": "bigint", "LINT": "bigint", "LTIME": "bigint", "LDATE": "bigint", "LDT": "bigint", "LTOD": "bigint"})


def _ident(name: str) -> str:
    n = re.sub(r"\W", "_", name)
    return n if not n[:1].isdigit() else "_" + n


def _closure(ts: TypeSystem, names: list[str]) -> list[DtEntry]:
    """Types plus every struct/enum/array element type they depend on, dependencies first."""
    out: list[DtEntry] = []
    seen: set[str] = set()

    def visit(tn: str) -> None:
        e = ts.get(tn)
        if e is None or e.name.lower() in seen:
            return
        seen.add(e.name.lower())
        for s in e.subitems:
            visit(s.type)
        if e.dims:
            visit(e.type)
        elif e.type and e.type.lower() != e.name.lower():
            visit(e.type)
        out.append(e)

    for n in names:
        visit(n)
    return out


def _is_scalar_name(tn: str) -> bool:
    up = tn.upper().split("(")[0]
    return up in CS_SCALAR or up.startswith(("STRING", "WSTRING"))


def to_csharp(ts: TypeSystem, type_names: list[str], namespace: str = "Transflo.Plc") -> str:
    lines = ["// Generated by twincat-mcp from the runtime datatype table. Offsets are the PLC's own.",
             "using System;", "using System.Runtime.InteropServices;", "", f"namespace {namespace}", "{"]
    for e in _closure(ts, type_names):
        if e.enum:
            base = {1: "sbyte", 2: "short", 4: "int", 8: "long"}.get(e.size, "short")
            lines.append(f"    public enum {_ident(e.name)} : {base}")
            lines.append("    {")
            for v, n in sorted(e.enum.items()):
                lines.append(f"        {_ident(n)} = {v},")
            lines.append("    }")
            lines.append("")
            continue
        if e.dims or not e.subitems:
            continue  # arrays/aliases/scalars are expressed inline
        lines.append(f"    [StructLayout(LayoutKind.Explicit, Size = {e.size}, Pack = 1)]")
        lines.append(f"    public struct {_ident(e.name)}")
        lines.append("    {")
        for s in e.subitems:
            if s.flags & F_REFERENCETO:
                lines.append(f"        [FieldOffset({s.offs})] public {'ulong' if s.size == 8 else 'uint'} {_ident(s.name)}; // {s.type} (pointer)")
                continue
            cs = _cs_field(ts, s)
            lines.append(f"        [FieldOffset({s.offs})] {cs} // {s.type}")
        lines.append("    }")
        lines.append("")
    lines.append("}")
    return "\n".join(lines)


def _cs_field(ts: TypeSystem, s: DtEntry) -> str:
    tn = s.type
    up = tn.upper()
    m = T._RE_STRING.match(tn)
    if m:
        n = int(m.group(1) or 80) + 1
        return f"[MarshalAs(UnmanagedType.ByValTStr, SizeConst = {n})] public string {_ident(s.name)};"
    m = T._RE_WSTRING.match(tn)
    if m:
        n = int(m.group(1) or 80) + 1
        return f"[MarshalAs(UnmanagedType.ByValArray, SizeConst = {n})] public char[] {_ident(s.name)};"
    arr = ts.get(tn)
    if s.dims or (arr is not None and arr.dims):
        e = arr if (arr is not None and arr.dims) else s
        count = e.element_count
        elem = e.type if (arr is not None and arr.dims) else (T._RE_ARRAY.match(tn).group(2).strip() if T._RE_ARRAY.match(tn) else tn)
        cs_elem = _cs_type(ts, elem)
        return f"[MarshalAs(UnmanagedType.ByValArray, SizeConst = {count})] public {cs_elem}[] {_ident(s.name)};"
    return f"{_cs_marshal(tn)}public {_cs_type(ts, tn)} {_ident(s.name)};"


def _cs_type(ts: TypeSystem, tn: str) -> str:
    up = tn.upper().split("(")[0]
    if up in CS_SCALAR:
        return CS_SCALAR[up][0]
    e = ts.get(tn)
    if e is not None and e.enum:
        return _ident(e.name)
    if e is not None and e.subitems:
        return _ident(e.name)
    if e is not None and e.type and e.type.lower() != e.name.lower() and not e.dims:
        return _cs_type(ts, e.type)
    return "byte"  # unknown: caller should check


def _cs_marshal(tn: str) -> str:
    return CS_SCALAR.get(tn.upper().split("(")[0], ("", ""))[1]


def to_typescript(ts: TypeSystem, type_names: list[str]) -> str:
    lines = ["// Generated by twincat-mcp from the runtime datatype table."]
    for e in _closure(ts, type_names):
        if e.enum:
            lines.append(f"export enum {_ident(e.name)} {{")
            for v, n in sorted(e.enum.items()):
                lines.append(f"  {_ident(n)} = {v},")
            lines.append("}")
            continue
        if e.dims or not e.subitems:
            continue
        lines.append(f"export interface {_ident(e.name)} {{")
        for s in e.subitems:
            lines.append(f"  {_ident(s.name)}: {_ts_type(ts, s.type)};  // {s.type} @{s.offs}")
        lines.append("}")
    return "\n".join(lines)


def _ts_type(ts: TypeSystem, tn: str) -> str:
    up = tn.upper().split("(")[0]
    if up in TS_SCALAR:
        return TS_SCALAR[up]
    if up.startswith(("STRING", "WSTRING")):
        return "string"
    e = ts.get(tn)
    if e is not None and e.dims:
        return f"{_ts_type(ts, e.type)}[]"
    m = T._RE_ARRAY.match(tn)
    if m:
        return f"{_ts_type(ts, m.group(2).strip())}[]"
    if e is not None and (e.enum or e.subitems):
        return _ident(e.name)
    if e is not None and e.type and e.type.lower() != e.name.lower():
        return _ts_type(ts, e.type)
    return "unknown"


def to_json(ts: TypeSystem, type_names: list[str]) -> str:
    return json.dumps({e.name: e.summary() for e in _closure(ts, type_names)}, indent=1)


def symbols_to_csharp(symbols: list[dict[str, Any]], class_name: str = "PlcSymbols", namespace: str = "Transflo.Plc") -> str:
    lines = ["// Generated by twincat-mcp: ADS symbol paths for AdsClient.ReadAny / CreateVariableHandle.",
             f"namespace {namespace}", "{", f"    public static class {class_name}", "    {"]
    for s in symbols:
        const = _ident(s["name"].replace(".", "_").replace("[", "_").replace("]", ""))
        lines.append(f"        /// <summary>{s['type']}</summary>")
        lines.append(f"        public const string {const} = \"{s['name']}\";")
    lines += ["    }", "}"]
    return "\n".join(lines)
